"""Iter-102: Legal Lens Professional Alignment Report cover page — contact block (title/bar/license), signature + date of submission,
and the word-count content-origin line (AI vs professional)."""
import io
import os

import pytest
import requests
from dotenv import load_dotenv
from pypdf import PdfReader

load_dotenv("/app/frontend/.env")
load_dotenv("/app/backend/.env")

from casekit import completed_case  # noqa: E402
from legal_lens import content_origin  # noqa: E402

API = f"{(os.environ.get('REACT_APP_BACKEND_URL') or '').rstrip('/')}/api"


def _text(b: bytes) -> str:
    return "\n".join(p.extract_text() or "" for p in PdfReader(io.BytesIO(b)).pages)


def test_content_origin_word_split():
    rep = {"joint_notes": "one two three four", "professional_summary": "five six", "ai_drafts": {"joint_notes": {"text": "one two three four"}}}
    o = content_origin(rep)
    assert (o["ai_pct"], o["pro_pct"], o["total_words"]) == (67, 33, 6)
    assert o["line"] == "Content origin: 67% generated by AI (reviewed by the professional) · 33% written by the professional."
    rep["joint_notes"] = "one two three four edited"
    assert content_origin(rep)["ai_pct"] == 0
    assert content_origin({})["line"] == "Content origin: no report text entered yet."


@pytest.fixture(scope="module")
def flow():
    pro, _pa, _pb, d, _ = completed_case(API)
    return pro, d["id"]


def test_cover_fields_and_pdf(flow):
    pro, rid = flow
    r = pro.put(f"{API}/cases/{rid}/professional-report", json={"fields": {
        "cover_title": "Attorney & Mediator", "cover_bar_number": "TX 24011111", "cover_license_number": "LIC-778", "submission_date": "2026-10-12",
        "joint_notes": "Portal-first communication keeps exchanges brief."}})
    assert r.status_code == 200, r.text
    v = pro.get(f"{API}/cases/{rid}/professional-report").json()
    p = v["professional"]
    assert (p["title"], p["bar_number"], p["license_number"], p["submission_date"]) == ("Attorney & Mediator", "TX 24011111", "LIC-778", "2026-10-12")
    assert v["content_origin"]["pro_pct"] == 100 and v["content_origin"]["line"].startswith("Content origin: 0% generated by AI")
    pdf = pro.get(f"{API}/cases/{rid}/professional-report/pdf")
    assert pdf.status_code == 200
    first = PdfReader(io.BytesIO(pdf.content)).pages[0].extract_text() or ""
    for needle in ("Bar Number", "TX 24011111", "License Number", "LIC-778", "Attorney & Mediator", "Professional signature", "Date of submission: 2026-10-12",
                   "Content origin: 0% generated by AI (reviewed by the professional)", "100% written by the professional"):
        assert needle in first, needle
    assert "Professional Alignment Report" in _text(pdf.content)

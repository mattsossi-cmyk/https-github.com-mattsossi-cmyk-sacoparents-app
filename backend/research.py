"""Perplexity Sonar research helper for professionals — cited answers and ZIP-based local resource lookup (review before use)."""
import json
import logging
import os
import re
import uuid
from datetime import datetime, timezone

import httpx
from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from lens_data import CHILD_FOCUS_CATEGORIES

logger = logging.getLogger("research")

AGENT_URL = "https://api.perplexity.ai/v1/agent"
SYSTEM = ("You assist a licensed family-law professional in Texas. Answer concisely with numbered inline citations [1], [2]. "
          "Never give legal advice, custody recommendations, or opinions about specific parents. If sources disagree, say so.")
LOCAL_CATEGORIES = {"parenting_facilitator": "parenting facilitators and parenting coordinators", "supervised_exchange": "supervised visitation and neutral child exchange services",
                    "dv_advocacy": "domestic violence advocacy, safety planning and protective-order assistance", "child_therapy": "child and family therapists experienced with separation and co-parenting",
                    "parent_education": "court-approved co-parenting and parent education classes"}
DISCLAIMER = "Web research generated by Perplexity (Agent API, web search). Verify every provider and citation before adding it to a report or the directory."


class AskIn(BaseModel):
    question: str = Field(min_length=3, max_length=2000)


class LocalIn(BaseModel):
    category: str
    zip: str = ""


class ZipIn(BaseModel):
    zip: str


class ProviderAddIn(BaseModel):
    name: str = Field(min_length=2, max_length=150)
    organization: str = ""
    phone: str = ""
    website: str = ""
    services: str = ""
    category: str = ""


def _split_providers(answer: str) -> tuple[str, list[dict]]:
    """Separate the prose from the trailing PROVIDERS_JSON block Sonar was asked to append."""
    if "PROVIDERS_JSON:" not in (answer or ""):
        return answer, []
    prose, _, tail = answer.partition("PROVIDERS_JSON:")
    m = re.search(r"\[.*\]", tail, re.S)
    try:
        items = json.loads(m.group(0)) if m else []
    except ValueError:
        items = []
    keys = ("name", "organization", "phone", "website", "services")
    return prose.strip(), [{k: str(i.get(k) or "")[:300] for k in keys} for i in items if isinstance(i, dict) and i.get("name")][:8]


async def sonar(question: str, recency: str | None = None) -> dict:
    key = os.environ.get("PERPLEXITY_API_KEY")
    if not key:
        raise HTTPException(status_code=503, detail="Research helper is not configured (PERPLEXITY_API_KEY missing)")
    return await _sonar_call(key, question, recency)


async def _sonar_call(key: str, question: str, recency: str | None) -> dict:
    """Perplexity Agent API (successor of Sonar): preset 'fast', built-in web search; sources come back as a search_results output item."""
    payload = {"preset": "fast", "input": question, "instructions": SYSTEM}
    try:
        async with httpx.AsyncClient(timeout=90) as client:
            r = await client.post(AGENT_URL, headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"}, json=payload)
            r.raise_for_status()
            data = r.json()
    except httpx.HTTPStatusError as e:
        logger.warning("perplexity %s: %s", e.response.status_code, e.response.text[:300])
        raise HTTPException(status_code=502, detail="Research request failed") from e
    except httpx.HTTPError as e:
        raise HTTPException(status_code=504, detail="Research service timed out") from e
    answer, urls = _parse_agent_output(data)
    return {"answer": answer, "citations": [{"index": i, "url": u} for i, u in enumerate(urls, 1)], "model": data.get("model") or "perplexity-agent", "disclaimer": DISCLAIMER}


def _parse_agent_output(data: dict) -> tuple[str, list[str]]:
    answer, urls = "", []
    for item in data.get("output") or []:
        if item.get("type") == "message":
            answer += "".join(c.get("text", "") for c in item.get("content") or [] if c.get("type") == "output_text")
        elif item.get("type") == "search_results":
            urls += [res.get("url") for res in sorted(item.get("results") or [], key=lambda x: x.get("id") or 0) if res.get("url")]
    return (answer or data.get("output_text") or "").strip(), list(dict.fromkeys(urls))


def _insight_question(rep: dict, zip_code: str) -> str:
    focus = [lbl for k, lbl in CHILD_FOCUS_CATEGORIES if (rep.get("child_focus") or {}).get(k, {}).get("checked")]
    pathways = rep.get("conflict_pathways") or []
    parts = [f"Provide a short evidence-based research summary (4-6 sentences, cite sources) for a family-court professional preparing a neutral co-parenting report. Joint co-parenting rating: {rep.get('joint_rating') or 'n/a'}/10."]
    if focus:
        parts.append("Child-focused issues identified: " + ", ".join(focus) + ".")
    if pathways:
        parts.append("Conflict-resolution pathways under consideration: " + ", ".join(pathways) + ".")
    parts.append("Cover: what current research says about these issues for children of separated parents, and which interventions (parenting coordination, structured communication, parent education, child therapy) show evidence of benefit.")
    if zip_code:
        parts.append(f"Then note, in one or two sentences, local resource availability near ZIP code {zip_code}, Texas (parenting facilitators, supervised exchange, parent education).")
    parts.append("Do not give legal advice or comment on specific parents.")
    return " ".join(parts)


async def research_insight(rep: dict, user: dict) -> dict | None:
    """Fetches the 'Research Base' for a professional report. Never raises — returns None when unconfigured or unreachable."""
    key = os.environ.get("PERPLEXITY_API_KEY")
    if not key:
        return None
    zip_code = ((user.get("profile") or {}).get("zip") or "").strip()
    try:
        res = await _sonar_call(key, _insight_question(rep, zip_code), "year")
    except Exception as exc:
        logger.warning("research insight unavailable: %s", exc)
        return None
    if not res.get("answer"):
        return None
    return {"text": res["answer"][:4000], "citations": res["citations"][:10], "model": res.get("model") or "sonar", "zip": zip_code, "fetched_at": datetime.now(timezone.utc).isoformat()}


def build_router(db, get_current_user) -> APIRouter:
    r = APIRouter()

    def _pro(user):
        if user.get("role") not in ("professional", "admin") or (user.get("role") == "professional" and not user.get("approved")):
            raise HTTPException(status_code=403, detail="Approved professional access required.")

    async def _store(user, kind, question, result):
        await db.research_queries.insert_one({"id": str(uuid.uuid4()), "user_id": user["_id"], "kind": kind, "question": question, "answer": result["answer"],
                                              "citations": result["citations"], "model": result.get("model"), "created_at": datetime.now(timezone.utc).isoformat()})

    @r.put("/me/profile/zip")
    async def set_zip(body: ZipIn, user=Depends(get_current_user)):
        z = body.zip.strip()[:10]
        await db.users.update_one({"_id": user["_id"]}, {"$set": {"profile.zip": z}})
        return {"zip": z}

    @r.get("/research/config")
    async def config(user=Depends(get_current_user)):
        _pro(user)
        return {"configured": bool(os.environ.get("PERPLEXITY_API_KEY")), "zip": ((user.get("profile") or {}).get("zip") or ""), "categories": [{"key": k, "label": v} for k, v in LOCAL_CATEGORIES.items()]}

    @r.post("/research/ask")
    async def ask(body: AskIn, user=Depends(get_current_user)):
        _pro(user)
        result = await sonar(body.question, recency="year")
        await _store(user, "ask", body.question, result)
        return result

    @r.post("/research/local-resources")
    async def local(body: LocalIn, user=Depends(get_current_user)):
        _pro(user)
        if body.category not in LOCAL_CATEGORIES:
            raise HTTPException(status_code=400, detail="Unknown category")
        z = (body.zip or (user.get("profile") or {}).get("zip") or "").strip()
        if not z:
            raise HTTPException(status_code=400, detail="Add your ZIP code to your professional profile first")
        q = (f"List up to 6 {LOCAL_CATEGORIES[body.category]} serving ZIP code {z} and the surrounding county in Texas. For each: organization name, phone, website, and one line on services. "
             "Only include providers you can cite. After the prose, append a line 'PROVIDERS_JSON:' followed by a JSON array of objects with keys name, organization, phone, website, services (strings, empty if unknown).")
        result = await sonar(q)
        result["answer"], result["providers"] = _split_providers(result["answer"])
        await _store(user, "local", q, result)
        return {**result, "zip": z, "category": body.category}

    @r.post("/research/providers/add")
    async def add_provider(body: ProviderAddIn, user=Depends(get_current_user)):
        if user.get("role") != "admin":
            raise HTTPException(status_code=403, detail="Admin access required")
        from providers import ProviderIn
        if await db.providers.find_one({"name": {"$regex": f"^{re.escape(body.name.strip())}$", "$options": "i"}}, {"_id": 1}):
            raise HTTPException(status_code=409, detail="A provider with this name is already in the directory")
        now = datetime.now(timezone.utc).isoformat()
        p = ProviderIn(name=body.name.strip()[:120], specialty=LOCAL_CATEGORIES.get(body.category, body.category)[:120].capitalize(), organization=body.organization.strip()[:150],
                       phone=body.phone.strip()[:40], website=body.website.strip()[:200], lists=["individual", "joint"])
        doc = {"id": str(uuid.uuid4()), **p.model_dump(), "source": "perplexity", "source_note": body.services.strip()[:400], "created_at": now, "updated_at": now}
        await db.providers.insert_one(dict(doc))
        return doc

    @r.post("/research/providers/{pid}/verify")
    async def verify_provider(pid: str, user=Depends(get_current_user)):
        if user.get("role") != "admin":
            raise HTTPException(status_code=403, detail="Admin access required")
        p = await db.providers.find_one({"id": pid}, {"_id": 0})
        if not p:
            raise HTTPException(status_code=404, detail="Provider not found")
        who = " ".join(x for x in (p.get("name"), p.get("organization"), "Texas") if x)
        q = (f"What are the current public phone number and official website for {who}? Also state whether the service still appears to be operating. Cite sources. "
             "After the prose, append a line 'PROVIDERS_JSON:' followed by a JSON array with ONE object with keys name, organization, phone, website, services.")
        result = await sonar(q)
        prose, found = _split_providers(result["answer"])
        cur = found[0] if found else {}
        norm = lambda s: re.sub(r"\D", "", s or "")  # noqa: E731
        site = lambda s: re.sub(r"^https?://(www\.)?|/$", "", (s or "").strip().lower())  # noqa: E731
        checks = {"phone": {"directory": p.get("phone", ""), "found": cur.get("phone", ""), "match": bool(cur.get("phone")) and norm(cur["phone"])[-10:] == norm(p.get("phone"))[-10:]},
                  "website": {"directory": p.get("website", ""), "found": cur.get("website", ""), "match": bool(cur.get("website")) and site(cur["website"]) == site(p.get("website"))}}
        verification = {"checked_at": datetime.now(timezone.utc).isoformat(), "checks": checks, "summary": prose[:1200], "citations": result["citations"][:6], "model": result.get("model")}
        await db.providers.update_one({"id": pid}, {"$set": {"verification": verification, "last_verified_at": verification["checked_at"]}})
        await _store(user, "verify", q, result)
        return {"verification": verification, "disclaimer": DISCLAIMER}

    @r.post("/research/providers/{pid}/apply-verification")
    async def apply_verification(pid: str, user=Depends(get_current_user)):
        if user.get("role") != "admin":
            raise HTTPException(status_code=403, detail="Admin access required")
        p = await db.providers.find_one({"id": pid}, {"_id": 0})
        if not p or not p.get("verification"):
            raise HTTPException(status_code=404, detail="Run a freshness check first")
        upd = {k: v["found"][:200] for k, v in p["verification"]["checks"].items() if v.get("found") and not v.get("match")}
        if upd:
            upd["updated_at"] = datetime.now(timezone.utc).isoformat()
            await db.providers.update_one({"id": pid}, {"$set": upd})
        return {"updated": {k: v for k, v in upd.items() if k != "updated_at"}}

    return r
